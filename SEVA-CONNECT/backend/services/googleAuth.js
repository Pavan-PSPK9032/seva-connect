/**
 * Google Identity Services ID-token verification.
 *
 * The browser obtains an ID token from Google Identity Services and sends the
 * raw `credential` string to the API. Nothing in the request body (email,
 * name, picture, role) is trusted: every identity field comes from the token
 * after Google's signature, issuer, audience and expiry checks.
 *
 * Only GOOGLE_CLIENT_ID is required for this flow. The client secret is not
 * used and must never be shipped to the browser.
 */
const { OAuth2Client } = require('google-auth-library');
const { normalizeEmail } = require('../utils/email');

const GOOGLE_ISSUERS = new Set(['accounts.google.com', 'https://accounts.google.com']);
const EMAIL_RE = /^\S+@\S+\.\S+$/;
const MAX_CREDENTIAL_LENGTH = 8192;
const MAX_CLOCK_SKEW_SECONDS = 300;

let cachedClient = null;
let cachedClientId = '';

function getClientId() {
  return String(process.env.GOOGLE_CLIENT_ID || '').trim();
}

function googleConfigured() {
  return Boolean(getClientId());
}

function getClient() {
  const id = getClientId();
  if (!cachedClient || cachedClientId !== id) {
    cachedClient = new OAuth2Client(id);
    cachedClientId = id;
  }
  return cachedClient;
}

function cleanName(value, email) {
  const fallback = String(email || '').split('@')[0] || 'Volunteer';
  const name = String(value || '')
    .replace(/[<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return (name || fallback).slice(0, 60);
}

function invalid(reason) {
  return { status: 'invalid', reason };
}

/**
 * @param {string} credential Raw Google ID token (`credential` from GIS).
 * @param {{nonce?: string}} [options] Nonce generated by the client and passed
 *   to `google.accounts.id.initialize`; when supplied it must be echoed in the
 *   token, which binds the token to this browser session.
 * @returns {Promise<
 *   | {status:'unconfigured'}
 *   | {status:'ok', profile:{sub:string,email:string,name:string,picture:string,emailVerified:true}}
 *   | {status:'expired'}
 *   | {status:'email_unverified'}
 *   | {status:'invalid', reason:string}
 * >}
 */
async function verifyGoogleIdToken(credential, options = {}) {
  const audience = getClientId();
  if (!audience) return { status: 'unconfigured' };

  if (
    typeof credential !== 'string' ||
    credential.length < 20 ||
    credential.length > MAX_CREDENTIAL_LENGTH
  ) {
    return invalid('malformed_credential');
  }

  let payload;
  try {
    const ticket = await getClient().verifyIdToken({ idToken: credential, audience });
    payload = ticket.getPayload();
  } catch (error) {
    // verifyIdToken rejects invalid signatures, wrong audiences, malformed
    // tokens and expired tokens. Never echo the raw token or Google's error.
    return invalid('signature_or_claims');
  }

  if (!payload || typeof payload !== 'object') return invalid('empty_payload');
  if (!GOOGLE_ISSUERS.has(payload.iss)) return invalid('issuer');
  if (payload.aud !== audience) return invalid('audience');

  const now = Math.floor(Date.now() / 1000);
  if (!Number.isFinite(payload.exp) || payload.exp <= now) return { status: 'expired' };
  if (Number.isFinite(payload.iat) && payload.iat > now + MAX_CLOCK_SKEW_SECONDS) {
    return invalid('issued_in_future');
  }

  if (payload.email_verified !== true && payload.email_verified !== 'true') {
    return { status: 'email_unverified' };
  }

  if (typeof payload.sub !== 'string' || !payload.sub) return invalid('subject');
  if (typeof payload.email !== 'string') return invalid('email');

  const email = normalizeEmail(payload.email);
  if (!EMAIL_RE.test(email)) return invalid('email');

  const nonce = String(options.nonce || '').trim();
  if (nonce) {
    if (typeof payload.nonce !== 'string' || payload.nonce !== nonce) {
      return invalid('nonce_mismatch');
    }
  }

  return {
    status: 'ok',
    profile: {
      sub: payload.sub,
      email,
      name: cleanName(payload.name, email),
      picture: typeof payload.picture === 'string' ? payload.picture : '',
      emailVerified: true,
    },
  };
}

module.exports = { verifyGoogleIdToken, googleConfigured, getClientId };
